# ── signing ───────────────────────────────────────────────────────────────────

def test_request_signature_matches_the_node_reference() -> None:
    """A byte-for-byte match with node:crypto's `signRequest`.

    Ed25519 is deterministic, so the same key over the same message yields the
    same signature in any correct implementation. A mismatch here means the
    wallet would answer AUTH_INVALID_SIGNATURE and say nothing further.
    """
    assert sign_request(VEC_PRIVATE, VEC_TIMESTAMP, VEC_BODY) == VEC_REQUEST_SIG


def test_public_key_derivation_matches_the_node_reference() -> None:
    assert public_key_b64(VEC_PRIVATE) == VEC_PUBLIC


def test_link_canonical_and_signature_match_the_node_reference() -> None:
    """The canonical string is the fragile half — one byte off and it's rejected."""
    canonical = canonical_create_message(
        public_key=VEC_PUBLIC,
        name="Errand Agent",
        platform="custom",
        description=VEC_DESCRIPTION,
        iat=1785000000,
    )
    assert canonical == VEC_CANONICAL
    assert (
        sign_create_params(
            VEC_PRIVATE,
            public_key=VEC_PUBLIC,
            name="Errand Agent",
            platform="custom",
            description=VEC_DESCRIPTION,
            iat=1785000000,
        )
        == VEC_CREATE_SIG
    )


def test_percent_encoding_follows_javascript_not_python() -> None:
    """`quote()`'s default safe set is not `encodeURIComponent`'s.

    Two differences bite: Python leaves `/` unescaped by default (JS escapes it,
    and base64 public keys are full of it), and JS leaves `!*'()~` alone.
    """
    assert js_encode_uri_component("a b/c~d!e*f'g(h)i%j+k") == "a%20b%2Fc~d!e*f'g(h)i%25j%2Bk"


def test_signature_verifies_and_is_bound_to_the_body() -> None:
    keys = generate_keypair()
    signature = sign_request(keys.private_key, "1700000000", '{"a":1}')
    assert verify_request(keys.public_key, "1700000000", '{"a":1}', signature)
    # A different body or timestamp must not verify — that binding is the whole
    # protection against a replayed or tampered request.
    assert not verify_request(keys.public_key, "1700000000", '{"a":2}', signature)
    assert not verify_request(keys.public_key, "1700000001", '{"a":1}', signature)


# ── the signed client ─────────────────────────────────────────────────────────

class _StubResponse:
    def __init__(self, status_code: int, payload: object) -> None:
        self.status_code = status_code
        self._payload = payload

    def json(self) -> object:
        return self._payload


class _StubHttpClient:
    """Stands in for httpx.AsyncClient, recording exactly what was sent."""

    def __init__(self, responses: list[_StubResponse]) -> None:
        self._responses = responses
        self.calls: list[dict] = []

    def __call__(self, *_args, **kwargs) -> "_StubHttpClient":
        self.timeout = kwargs.get("timeout")
        return self

    async def __aenter__(self) -> "_StubHttpClient":
        return self

    async def __aexit__(self, *_exc) -> bool:
        return False

    async def post(self, url: str, headers: dict, content: bytes) -> _StubResponse:
        self.calls.append({"url": url, "headers": headers, "content": content})
        return self._responses.pop(0)


def _with_stub_http(responses: list[_StubResponse], call):
    """Run `call(client)` against a stubbed transport, then put httpx back.

    Restoring matters: these modules share a process under a test runner, and a
    permanently monkeypatched `httpx.AsyncClient` would silently swallow every
    later HTTP call in the suite.
    """
    from app.prava import wallet as wallet_module

    stub = _StubHttpClient(responses)
    original = wallet_module.httpx.AsyncClient
    wallet_module.httpx.AsyncClient = stub  # type: ignore[assignment]
    try:
        return call(WalletClient("agent_test", VEC_PRIVATE)), stub
    finally:
        wallet_module.httpx.AsyncClient = original  # type: ignore[assignment]


def test_client_signs_the_exact_bytes_it_sends() -> None:
    """The signed message must be the body on the wire, not a re-serialization.

    This is the failure that produces a valid-looking request the server refuses:
    sign a dict, then let httpx serialize it again with different separators, and
    the two disagree by two characters per key.
    """
    _, stub = _with_stub_http(
        [_StubResponse(200, {"success": True, "data": {"ok": 1}})],
        lambda client: asyncio.run(
            client.post("/v1/wallet/shop/search", {"query": "coffee", "limit": 5})
        ),
    )

    sent = stub.calls[0]
    body_on_the_wire = sent["content"].decode()
    assert body_on_the_wire == '{"query":"coffee","limit":5}'
    assert verify_request(
        VEC_PUBLIC,
        sent["headers"]["X-Timestamp"],
        body_on_the_wire,
        sent["headers"]["X-Signature"],
    )
    assert sent["headers"]["X-Agent-Id"] == "agent_test"
    assert sent["headers"]["X-Skill-Name"] == "prava-shopping"
    # Unix SECONDS. A millisecond timestamp reads as ~55,000 years hence and the
    # server rejects it as expired.
    assert len(sent["headers"]["X-Timestamp"]) == 10


def test_client_raises_the_servers_own_error_code() -> None:
    try:
        _with_stub_http(
            [
                _StubResponse(
                    401,
                    {"error": {"code": "AUTH_INVALID_SIGNATURE", "message": "Missing or expired signature"}},
                )
            ],
            lambda client: asyncio.run(client.post("/v1/wallet/shop/search", {"query": "x"})),
        )
    except WalletError as exc:
        assert exc.code == "AUTH_INVALID_SIGNATURE"
        assert exc.status == 401
        assert "signature" in str(exc).lower()
    else:  # pragma: no cover
        raise AssertionError("expected WalletError")


def test_client_treats_a_200_with_success_false_as_a_failure() -> None:
    """The wallet reports declines inside a 200 envelope."""
    try:
        _with_stub_http(
            [
                _StubResponse(
                    200,
                    {"success": False, "error": {"code": "SHOP_SESSION_EXPIRED", "message": "expired"}},
                )
            ],
            lambda client: asyncio.run(client.post("/v1/wallet/shop/checkout", {})),
        )
    except WalletError as exc:
        assert exc.code == "SHOP_SESSION_EXPIRED"
    else:  # pragma: no cover
        raise AssertionError("expected WalletError")


def test_client_surfaces_the_replayed_flag() -> None:
    """A replay is a prior terminal result, NOT a fresh charge."""
    try:
        _with_stub_http(
            [
                _StubResponse(
                    200,
                    {"success": False, "replayed": True, "error": {"code": "X", "message": "already processed"}},
                )
            ],
            lambda client: asyncio.run(client.post("/v1/wallet/shop/checkout", {})),
        )
    except WalletError as exc:
        assert exc.replayed is True
    else:  # pragma: no cover
        raise AssertionError("expected WalletError")


