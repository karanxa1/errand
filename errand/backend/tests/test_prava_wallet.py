def test_build_cart_quotes_the_cheapest_allowed_variant() -> None:
    wallet = _FakeWallet(
        {
            "/v1/wallet/shop/search": _search_hit(),
            "/v1/wallet/shop/product": _product([_variant("v-expensive", 4999), _variant("v-cheap", 1999)]),
            "/v1/wallet/shop/quote": _quote(),
        }
    )
    broker = PravaShopBroker(wallet)  # type: ignore[arg-type]
    cart = asyncio.run(broker.build_cart("https://bonescoffee.com", "buy coffee", _context()))

    quoted = [body for path, body in wallet.calls if path == "/v1/wallet/shop/quote"]
    assert quoted[0]["variant_id"] == "v-cheap"
    assert cart.total_cents == 2798
    assert cart.checkout.session_ref == "checkout_1"
    # The rows a human reads before approving MUST add up to what is charged.
    assert sum(i.qty * i.price_cents for i in cart.items) == cart.total_cents
    assert [i.name for i in cart.items] == ["Costa Rica Single-Origin", "Shipping"]


def test_build_cart_never_leaves_the_approved_merchant() -> None:
    """`product` lists every seller of an item; only the pinned one is buyable.

    The card `run_errand` mints is scoped to the policy merchant, so a variant
    from another seller is both a policy breach and a guaranteed decline.
    """
    wallet = _FakeWallet(
        {
            "/v1/wallet/shop/search": _search_hit(),
            "/v1/wallet/shop/product": _product(
                [_variant("v-other", 999, domain="cheapcoffee.example"), _variant("v-ours", 1999)]
            ),
            "/v1/wallet/shop/quote": _quote(),
        }
    )
    broker = PravaShopBroker(wallet)  # type: ignore[arg-type]
    asyncio.run(broker.build_cart("https://bonescoffee.com", "buy coffee", _context()))
    quoted = [body for path, body in wallet.calls if path == "/v1/wallet/shop/quote"]
    assert quoted[0]["variant_id"] == "v-ours"


