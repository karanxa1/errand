"""Prava wallet integration — signing, the signed client, and the shop broker.

No network. Every wallet call is driven against a stub, so nothing here can
reach pay-api.prava.space and no spend is possible.

The signing cases carry KNOWN-ANSWER VECTORS produced by the reference
implementation itself (`@prava-sdk/cli` v3.1.0, node:crypto). That is the point
of them: a Python signature that merely round-trips against Python proves
nothing about whether Prava's server will accept it. These bytes came out of
Node, and if a refactor changes ours, these fail.

Runs under pytest, and standalone (`uv run python tests/test_prava_wallet.py`),
matching the house style in this directory.
"""

