def test_expired_quote_is_repriced_and_paid_when_the_total_holds() -> None:
    """Approval + card entry can outlast a ~5 minute quote; that must recover."""
    state = {"checkout_calls": 0}

    def checkout(body: dict, _n: int) -> dict:
        state["checkout_calls"] += 1
        if body["checkout_session_id"] == "checkout_1":
            raise WalletError("Quote expired", code="SHOP_SESSION_EXPIRED")
        return {"status": "paid", "order_id": "ord_9", "amount": {"amount": "27.98", "currency": "USD"}}

    wallet = _FakeWallet(
        {
            "/v1/wallet/shop/search": _search_hit(),
            "/v1/wallet/shop/product": _product([_variant("v1", 1999)]),
            "/v1/wallet/shop/quote": lambda body, n: _quote(session=f"checkout_{n}"),
            "/v1/wallet/shop/checkout": checkout,
        }
    )
    broker = PravaShopBroker(wallet)  # type: ignore[arg-type]
    cart = asyncio.run(broker.build_cart("https://bonescoffee.com", "buy coffee", _context()))
    order = asyncio.run(broker.complete_checkout(cart.checkout, _CREDENTIAL))
    assert order.order_id == "ord_9"
    assert state["checkout_calls"] == 2


def test_a_price_that_moved_is_refused_rather_than_charged() -> None:
    """The card is scoped to the approved total. A different one is not ours to pay."""

    def checkout(body: dict, _n: int) -> dict:
        if body["checkout_session_id"] == "checkout_1":
            raise WalletError("Quote expired", code="SHOP_SESSION_EXPIRED")
        return {"status": "paid", "order_id": "ord_should_not_happen"}

    def quote(_body: dict, n: int) -> dict:
        # Second quote comes back dearer than the one the human approved.
        return _quote("31.98" if n > 1 else "27.98", session=f"checkout_{n}")

    wallet = _FakeWallet(
        {
            "/v1/wallet/shop/search": _search_hit(),
            "/v1/wallet/shop/product": _product([_variant("v1", 1999)]),
            "/v1/wallet/shop/quote": quote,
            "/v1/wallet/shop/checkout": checkout,
        }
    )
    broker = PravaShopBroker(wallet)  # type: ignore[arg-type]
    cart = asyncio.run(broker.build_cart("https://bonescoffee.com", "buy coffee", _context()))
    try:
        asyncio.run(broker.complete_checkout(cart.checkout, _CREDENTIAL))
    except PravaShopError as exc:
        assert exc.code == "PRICE_MOVED"
        assert "27.98" in str(exc) and "31.98" in str(exc)
    else:  # pragma: no cover
        raise AssertionError("a moved price must never be charged silently")
    # Exactly one checkout attempt reached the wallet — the second was refused
    # locally, before any card was presented.
    assert len([c for c in wallet.calls if c[0] == "/v1/wallet/shop/checkout"]) == 1


def _run_all() -> None:
    for name, fn in sorted(globals().items()):
        if name.startswith("test_") and callable(fn):
            fn()
            print(f"  ok  {name}")


if __name__ == "__main__":
    _run_all()
    print("\nall wallet tests passed")
