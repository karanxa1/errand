class _FakeWallet:
    """Scripted wallet: maps a path to a response or a raiser."""

    def __init__(self, routes: dict[str, object]) -> None:
        self.routes = routes
        self.calls: list[tuple[str, dict]] = []

    async def post(self, path: str, body: dict | None = None, *, timeout_s: float = 30.0) -> dict:
        self.calls.append((path, body or {}))
        handler = self.routes[path]
        if callable(handler):
            return handler(body or {}, len([c for c in self.calls if c[0] == path]))
        if isinstance(handler, Exception):
            raise handler
        return handler  # type: ignore[return-value]


def _context(budget_cents: int = 20000, rules: list[str] | None = None) -> PurchaseContext:
    return PurchaseContext(
        profile="business",
        approved_merchants=[Merchant(name="Bones Coffee", url="https://bonescoffee.com")],
        budget_cents=budget_cents,
        rules=rules if rules is not None else [],
    )


def _search_hit(product_id: str = "p1", title: str = "Costa Rica Single-Origin") -> dict:
    return {
        "results": [
            {"product_id": product_id, "merchant": "bonescoffee.com", "title": title,
             "price_estimate": {"amount": "19.99", "currency": "USD"}}
        ],
        "has_more": False,
    }


def _product(variants: list[dict]) -> dict:
    return {"product": {"id": "p1", "merchant": "bonescoffee.com", "variants": variants}}


def _variant(vid: str, price_cents: int, *, domain: str = "bonescoffee.com", available: bool = True, label: str = "12oz whole bean") -> dict:
    return {
        "id": vid,
        "label": label,
        "priceAmount": price_cents,
        "currency": "USD",
        "available": available,
        "options": [],
        "merchantDomain": domain,
    }


def _quote(total: str = "27.98", *, session: str = "checkout_1", subtotal: int = 1999, shipping: int = 799, tax: int = 0) -> dict:
    return {
        "checkout_session_id": session,
        "merchant": "bonescoffee.com",
        "final_price": {"amount": total, "currency": "USD"},
        "price_breakdown": {
            "subtotal_cents": subtotal,
            "shipping_cents": shipping,
            "tax_cents": tax,
            "currency": "USD",
        },
        "expires_at": "2026-08-02T18:30:00.000Z",
    }


